// ── Motifs (header patterns with a reason) ─────────────────────────────────────────────────────────────────────────
// module → motif is generated by tools/gen_motifs.py (see ui_design/pattern-map.md). A motif is only ever used inside
// one category, and depicts what the module does to the picture.
export const MOTIFS = MOTIF_DATA.motifs

export function motifOf(programId, categoryId) {
  return MOTIF_DATA.programs[programId] || MOTIF_DATA.categories[categoryId] || null
}

export function categoryMotif(categoryId) {
  return MOTIF_DATA.categories[categoryId] || null
}

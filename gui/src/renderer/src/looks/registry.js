// Default family for every program of a category.
const CATEGORY_FAMILY = {
  glitch: 'glitch', trails: 'trails', temporal: 'motion', look: 'color', vision: 'vision',
  layout: 'layout', edit: 'cut', speech: 'speech', media: 'media'
}

// Programs that look/behave like a different family than their category suggests.
const OVERRIDES = {
  texture: ['halftone', 'dither', 'retro_dither', 'ordered_dither', 'ascii_art', 'pixelate', 'kmeans_palette', 'led_wall',
            'posterize', 'oil_paint', 'emboss', 'sketch', 'cartoon', 'blur_pix', 'old_film_damage'],
  warp:    ['warp', 'flow_warp', 'little_planet', 'tunnel', 'slit_scan', 'face_warp', 'topobeaux', 'shape_synth', 'stackadelic'],
  glitch:  ['recalled_sensor', 'recalled_sensor_pro', 'pixel_sort'],
  weird:   ['fever', 'double_cup', 't1000', 'bad_predator', 'ghostee', 'zapruder', 'soapblind', 'ball_point_pen', 'light_snow',
            'repainting', 'smudge', 'deep_fry', 'crossmosh', 'lsd_feedback', 'lsd_feedback_pro', 'nostalgic_stutter',
            'overexposed_stutter', 'steel_wash', 'pickle_juice', 'septic', 'wbflare', 'wbflare_pro', 'rb_blur', 'rb_blur_pro']
}
const OVERRIDE_MAP = Object.fromEntries(
  Object.entries(OVERRIDES).flatMap(([fam, ids]) => ids.map(id => [id, fam]))
)

export function familyOfCategory(categoryId) {
  return CATEGORY_FAMILY[categoryId] || 'media'
}

export function familyOf(programId, categoryId) {
  return OVERRIDE_MAP[programId] || familyOfCategory(categoryId)
}


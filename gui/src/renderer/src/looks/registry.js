// Visual identity registry: which "pattern family" a program belongs to.
//
// A family is a *visual* layer on top of the existing categories — it decides which Memphis-style motif a module wears,
// nothing else. Presets, processing and the sidebar's category list are untouched. Under the Classic look none of this is
// drawn (the data-family attributes simply have no CSS attached).


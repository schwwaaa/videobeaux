#!/usr/bin/env python3
"""
Generate gui/src/renderer/src/looks/shared/patterns.css — the original Memphis-style header patterns used by the
non-Classic Looks. Every motif is drawn here (squiggles, zig-zags, dots, plus signs, bricks, arcs ...); nothing is copied
from third-party artwork.

    python tools/gen_look_patterns.py

Each family is a 64x32 tile of two translucent marks (dark + light) so it sits on any header colour, in light or dark mode,
without hurting the title text.
"""
import urllib.parse
from pathlib import Path

D = "rgba(8,8,8,0.30)"        # dark marks
L = "rgba(255,253,246,0.60)"  # light marks
W, H = 64, 32


def S(body: str) -> str:
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">{body}</svg>'


def rect(x, y, w, h, c, r=0):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="{c}"/>'


def line(d, c, w=2.4, dash=None):
    da = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round"{da}/>'


def circ(x, y, r, c, fill=True, w=2):
    return (f'<circle cx="{x}" cy="{y}" r="{r}" fill="{c}"/>' if fill
            else f'<circle cx="{x}" cy="{y}" r="{r}" fill="none" stroke="{c}" stroke-width="{w}"/>')


def tri(a, b, c_, col):
    return f'<polygon points="{a[0]},{a[1]} {b[0]},{b[1]} {c_[0]},{c_[1]}" fill="{col}"/>'


FAMILIES = {}

# Glitch & Corruption — broken pixel fragments
FAMILIES["glitch"] = "".join([
    rect(4, 4, 10, 4, D), rect(18, 11, 6, 3, L), rect(30, 3, 12, 5, D), rect(46, 10, 8, 3, L), rect(8, 21, 14, 3, L),
    rect(27, 24, 6, 5, D), rect(39, 18, 10, 4, D), rect(54, 23, 7, 6, L), rect(52, 2, 6, 3, L), rect(1, 14, 4, 4, D),
])
# Trails & Echoes — receding arcs
FAMILIES["trails"] = "".join(
    [line(f"M0 {32 - r} A{r} {r} 0 0 1 {r} 32", D, 2.2) for r in (8, 16, 24)] +
    [line(f"M{64 - r} 0 A{r} {r} 0 0 1 64 {r}", L, 2.2) for r in (8, 16, 24)]
)
# Time & Motion — waves
FAMILIES["motion"] = (line("M0 10 Q8 2 16 10 T32 10 T48 10 T64 10", D) + line("M0 24 Q8 16 16 24 T32 24 T48 24 T64 24", L) +
                      circ(58, 4, 1.8, D))
# Pixel & Texture — halftone
FAMILIES["texture"] = "".join(circ(4 + 8 * i, 4 + 8 * j, 0.7 + 1.9 * i / 7, D if (i + j) % 2 == 0 else L)
                              for i in range(8) for j in range(4))
# Color & Light — rays
FAMILIES["color"] = "".join(
    [line(f"M32 34 L{x} 0", L, 2) for x in (4, 14, 24, 32, 40, 50, 60)] + [circ(10, 8, 2, D), circ(54, 10, 2, D), circ(32, 22, 3, D)]
)
# Warp & Geometry — spiral + bent lines
FAMILIES["warp"] = (line("M32 16 C34 13 38 15 36 19 C34 24 26 22 27 16 C28 9 38 7 43 13", D, 2.4) +
                    line("M0 6 Q16 -2 32 6 T64 6", L, 2) + line("M0 28 Q16 20 32 28 T64 28", L, 2))
# Vision & Tracking — reticles
FAMILIES["vision"] = (circ(16, 16, 7, D, False) + line("M16 4 V28 M4 16 H28", D, 2) + circ(48, 16, 4, L, False) +
                      line("M36 16 H60", L, 1.6, "2 4") + circ(48, 16, 1.2, L))
# Layout & Overlay — bricks
FAMILIES["layout"] = "".join(
    [f'<rect x="{x}" y="3" width="14" height="7" fill="none" stroke="{L}" stroke-width="2"/>' for x in (0, 16, 32, 48)] +
    [f'<rect x="{x}" y="13" width="14" height="7" fill="none" stroke="{L}" stroke-width="2"/>' for x in (-8, 8, 24, 40, 56)] +
    [f'<rect x="{x}" y="23" width="14" height="7" fill="none" stroke="{L}" stroke-width="2"/>' for x in (0, 16, 32, 48)] +
    [rect(18, 15, 10, 3, D), rect(50, 5, 10, 3, D)]
)
# Cut & Assemble — dashed cuts
FAMILIES["cut"] = (line("M-4 36 L36 -4", D, 2.2, "5 4") + line("M28 36 L68 -4", D, 2.2, "5 4") + rect(8, 6, 5, 5, L) + rect(44, 20, 5, 5, L))
# Speech & Captions — dots + quote ticks
FAMILIES["speech"] = (circ(6, 8, 2, D) + circ(14, 8, 2, D) + circ(22, 8, 2, D) + line("M36 5 q5 -3 5 3 q0 5 -5 5", D, 2.2) +
                      line("M48 5 q5 -3 5 3 q0 5 -5 5", D, 2.2) + rect(4, 20, 24, 8, "none", 4).replace('fill="none"', f'fill="none" stroke="{L}" stroke-width="2"') +
                      circ(44, 24, 2, L))
# Media Tools — confetti
FAMILIES["media"] = (tri((6, 26), (13, 26), (9.5, 18), D) + line("M30 5 v9 M25.5 9.5 h9", L, 2.4) + line("M42 24 q3 -7 6 0 t6 0", D, 2.2) +
                     circ(54, 8, 2, L) + circ(20, 14, 1.6, L) + rect(56, 22, 5, 5, D))
# Experimental / Weird — erratic squiggles
FAMILIES["weird"] = (line("M2 9 L10 2 L16 13 L24 4 L31 15", D, 2.4) + tri((40, 29), (49, 29), (44.5, 20), L) +
                     line("M36 8 q4 -6 8 0 t8 0 t8 0", L, 2.2) + line("M54 20 l6 6 M60 20 l-6 6", D, 2.2))


def data_uri(svg: str) -> str:
    return "data:image/svg+xml," + urllib.parse.quote(svg, safe="/:=,()' ")


def build_css() -> str:
    out = [
        "/* GENERATED by tools/gen_look_patterns.py — do not edit by hand. Original motifs; inert under the Classic look. */",
        ":root[data-look] {",
    ]
    for fam, body in FAMILIES.items():
        out.append(f'  --pat-{fam}: url("{data_uri(S(body))}");')
    out.append("}")
    for fam in FAMILIES:
        out.append(f':root[data-look] [data-family="{fam}"] {{ --pat: var(--pat-{fam}); }}')
    out.append("""
/* Look "Patterns" (v1): header strips, category chips and sidebar swatches take their *family's* pattern.
   The title always sits on a solid chip of the header colour, so text contrast is exactly what Classic has. */
:root[data-look="patterns"] .node-header[data-family] {
  background-image: var(--pat);
  background-size: 64px 32px;
  background-position: 0 0;
}
:root[data-look] .node-header[data-family] > span:not(.node-glyph) {
  flex: 0 1 auto !important;
  margin-right: auto;
  background-color: var(--node-color);
  padding: 1px 7px;
  border-radius: 6px;
}
:root[data-look="patterns"] .cat-chip[data-family] {
  background-image: linear-gradient(90deg, var(--node-color) 0 60%, transparent 92%), var(--pat);
  background-size: 100% 100%, 64px 32px;
}
:root[data-look="patterns"] .prog-dot[data-family] {
  width: 20px !important; height: 13px !important; border-radius: 3px !important;
  background-image: var(--pat); background-size: 32px 16px;
}
""")
    return "\n".join(out)


if __name__ == "__main__":
    dest = Path(__file__).resolve().parents[1] / "gui/src/renderer/src/looks/shared/patterns.css"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(build_css(), encoding="utf-8")
    print(f"wrote {dest} ({dest.stat().st_size // 1024} KB, {len(FAMILIES)} families)")
